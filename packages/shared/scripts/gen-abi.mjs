// Regenerates src/abi.ts from Foundry build output. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../../../contracts/out/", import.meta.url);
const pick = (file, name) => JSON.parse(readFileSync(new URL(`${file}/${name}.json`, root))).abi;
const out = [
  ["deliveryCheckoutAbi", pick("DeliveryCheckout.sol", "DeliveryCheckout")],
  ["openBoxAccountAbi", pick("OpenBoxAccount.sol", "OpenBoxAccount")],
  ["openBoxAccountFactoryAbi", pick("OpenBoxAccount.sol", "OpenBoxAccountFactory")],
  ["mockUsdtAbi", pick("MockUSDT.sol", "MockUSDT")],
];
let src = "// GENERATED by scripts/gen-abi.mjs from contracts/out. Do not edit.\n";
for (const [n, abi] of out) src += `export const ${n} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
writeFileSync(new URL("../src/abi.ts", import.meta.url), src);
console.log("wrote src/abi.ts");
